#!/usr/bin/env bash
# Источник: t.me/aidvizhenie · admin h-i-l-artem · канал и гиг: aidvizh_hub

# Строгий режим — ПЕРВОЙ исполняемой строкой (единый гейт набора считает
# строгость по первым 25 строкам; выше — только комментарии).
set -euo pipefail

# gitleaks pre-commit обёртка (28.08): если gitleaks установлен —
# сканирует staged; нет — честный пропуск (CI gitleaks догонит).
# Не роняет коммит отсутствием бинарника (двухслойная оборона, но
# не блокер локальной разработки).

# rc сканера ПРОБРАСЫВАЕТСЯ (exec): раньше ниже стоял безусловный `exit 0`,
# из-за чего guard-all.sh физически не мог остановить коммит (аудит 21.09).
#
# Почему строгий режим тут ничего не ломает (bats: tests/bats/gitleaks_precommit.bats):
# веток ровно две, unset-переменных нет, внешних утилит кроме самого сканера — тоже
# (command -v и printf — встроенные); отсутствие сканера остаётся честным rc 0
# через явную ветку ниже.

if command -v gitleaks >/dev/null 2>&1; then
  exec gitleaks protect --staged --verbose
fi
echo "gitleaks не установлен локально — секрет-скан сделает CI (gitleaks.yml)"
exit 0
